"""Deterministic ranking parity: pinned to output of the pre-integration app.py (git 2b0f33c).

``tests/ranking_golden_v1.json`` was generated by running the original
``app.analyze_resume`` against the synthetic fixtures with ``BagOfWordsEncoder``.
Any change here means scores, components, labels, or order changed.
"""

import json
from pathlib import Path

import pytest

from services.ranking import analyze_resume_bytes, build_export_frame, rank_results
from utils.scoring import DEFAULT_WEIGHTS

from ranking_fixtures import BagOfWordsEncoder, JOB, resume_files


GOLDEN = json.loads((Path(__file__).parent / "ranking_golden_v1.json").read_text())


def run(blind):
    job = dict(JOB, blind_review=blind)
    results = [
        analyze_resume_bytes(name, data, index, job, BagOfWordsEncoder())
        for index, (name, data) in enumerate(resume_files(), start=1)
    ]
    return rank_results(results)


def test_default_weights_are_unchanged():
    assert DEFAULT_WEIGHTS == {"semantic": 0.40, "required_skills": 0.35, "preferred_skills": 0.10, "experience": 0.15}


@pytest.mark.parametrize("blind", [True, False])
def test_scores_components_and_order_match_original_app(blind):
    results = run(blind)
    observed = [{key: item[key] for key in GOLDEN[str(blind)][0]} for item in results]
    assert observed == GOLDEN[str(blind)]
    assert [item["rank"] for item in results] == [1, 2, 3]


def test_ranking_is_deterministic_for_identical_inputs():
    assert [(r["candidate"], r["score"]) for r in run(True)] == [(r["candidate"], r["score"]) for r in run(True)]


def test_blind_mode_never_exposes_filenames_or_direct_identifiers():
    results = run(True)
    rendered = json.dumps(results) + build_export_frame(results).to_csv(index=False)
    for name, _ in resume_files():
        assert name not in rendered and name.split()[0] not in rendered
    assert "blair.sample@example.com" not in rendered


def test_gemini_is_not_called_without_key_and_scores_are_unaffected():
    results = run(True)
    assert {item["genai"]["status"] for item in results} == {"disabled"}
